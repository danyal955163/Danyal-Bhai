import { NextRequest, NextResponse } from 'next/server';

function escapeHtml(value: string) {
  return value.replace(/[&<>'"]/g, (character) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    "'": '&#39;',
    '"': '&quot;',
  })[character] ?? character);
}

export async function POST(request: NextRequest) {
  try {
    const { content, title } = await request.json();
    if (typeof content !== 'string' || !content.trim()) {
      return NextResponse.json({ error: 'Content required' }, { status: 400 });
    }

    const safeTitle = escapeHtml(typeof title === 'string' && title.trim() ? title : 'Danyal AI Document');
    const safeContent = escapeHtml(content);
    const html = `<!DOCTYPE html>
<html><head><meta charset="UTF-8"><title>${safeTitle}</title>
<style>body{font-family:Arial,sans-serif;padding:40px;line-height:1.6}h1{color:#10B981;border-bottom:2px solid #10B981;padding-bottom:10px}.content{white-space:pre-wrap}.footer{margin-top:40px;text-align:center;color:#999;font-size:12px}@media print{body{padding:0}}</style>
</head><body><h1>${safeTitle}</h1><div class="content">${safeContent}</div><div class="footer">Generated by Danyal AI</div></body></html>`;

    return new NextResponse(html, { headers: { 'Content-Type': 'text/html; charset=utf-8' } });
  } catch (error) {
    return NextResponse.json({ error: error instanceof Error ? error.message : 'Unable to generate document' }, { status: 500 });
  }
}
